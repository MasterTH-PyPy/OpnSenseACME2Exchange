// ───────────────────────── Engine (End-to-End mit Fakes) ─────────────────────────
(AppConfig Cfg, FakeOpnSense Opn, FakeExchange Ex, string NewThumb, string OldThumb) Scenario()
{
    var (newPem, newThumb) = pki.Leaf(new[] { "mail.example.de", "autodiscover.example.de" }, now.AddDays(-1), now.AddDays(89));
    var (oldPem, oldThumb) = pki.Leaf(new[] { "mail.example.de", "autodiscover.example.de" }, now.AddDays(-80), now.AddDays(9));
    var (wwwPem, _) = pki.Leaf(new[] { "www.example.de" }, now.AddDays(-1), now.AddDays(120));

    var opn = new FakeOpnSense();
    foreach (var host in new[] { "fw1", "fw2" })
    {
        opn.Files[host] = new Dictionary<string, string>
        {
            ["/usr/local/etc/haproxy.conf"] = HaproxyConf,
            ["/tmp/haproxy/ssl/60a1b2c3.certlist"] = "/tmp/haproxy/ssl/www.pem\n/tmp/haproxy/ssl/exch.pem mail.example.de\n/tmp/haproxy/ssl/missing.pem\n",
            ["/tmp/haproxy/ssl/www.pem"] = wwwPem,
            ["/tmp/haproxy/ssl/exch.pem"] = newPem,
            ["/tmp/haproxy/ssl/direct.pem"] = oldPem,
            ["/tmp/haproxy/mapfiles/60a2.txt"] = "owa.example.de exchange_backend\n"
        };
    }
    opn.CarpOutput["fw1"] = "\tcarp: BACKUP vhid 1 advbase 1 advskew 100\n";
    opn.CarpOutput["fw2"] = "\tcarp: MASTER vhid 1 advbase 1 advskew 0\n\tcarp: MASTER vhid 2 advbase 1 advskew 0\n";

    var ex = new FakeExchange();
    var oldEx = new ExchangeCertInfo(oldThumb, "CN=mail.example.de", "CN=Test Intermediate R1", null,
        DateTime.Now.AddDays(-80), DateTime.Now.AddDays(9), new[] { "IIS" }, new[] { "mail.example.de", "autodiscover.example.de" }, true);
    ex.Stores["exch1.corp.local"] = new() { oldEx };
    ex.Stores["exch2.corp.local"] = new() { oldEx };

    var cfg = new AppConfig();
    cfg.OpnSense.Nodes.Add(new OpnSenseNode { Name = "FW1", Host = "fw1" });
    cfg.OpnSense.Nodes.Add(new OpnSenseNode { Name = "FW2", Host = "fw2" });
    cfg.Selection.SectionKey = "frontend 1_HTTPS_frontend";
    cfg.Selection.ExchangeHostname = "mail.example.de";
    cfg.Selection.AdditionalRequiredNames.Add("autodiscover.example.de");
    cfg.Exchange.Servers.Add(new ExchangeServerEntry { Name = "EXCH1", Fqdn = "exch1.corp.local" });
    cfg.Exchange.Servers.Add(new ExchangeServerEntry { Name = "EXCH2", Fqdn = "exch2.corp.local" });
    return (cfg, opn, ex, newThumb, oldThumb);
}

DeployEngine Engine(AppConfig cfg, FakeOpnSense opn, FakeExchange ex) =>
    new(cfg, new OpnSenseCertificateSource(cfg.OpnSense, opn), ex, ex, (_, _) => { }) { VerifyDelay = TimeSpan.Zero, RetryDelay = TimeSpan.Zero };

Test("Engine: CARP-Master zuerst, richtiges Zertifikat, Tausch auf beiden Servern, verifiziert", () =>
{
    var (cfg, opn, ex, newThumb, oldThumb) = Scenario();
    var r = Engine(cfg, opn, ex).Run(false, CancellationToken.None);
    Assert.True(r.Success, "Erfolg: " + r.Summary + " " + r.FatalError);
    Assert.Equal(newThumb, r.Certificate!.Thumbprint, "neues Zertifikat gewählt (nicht www, nicht alt)");
    Assert.True(r.CertificateSource!.StartsWith("FW2"), "vom CARP-Master: " + r.CertificateSource);
    Assert.True(r.Servers.All(s => s.Outcome == ServerOutcome.Ok), "beide OK");
    Assert.True(r.Servers.All(s => s.Details.Contains("Verifiziert")), "verifiziert");
    Assert.True(ex.Stores["exch1.corp.local"].Single(c => c.Thumbprint == newThumb).HasService("IIS"), "IIS gebunden");
    Assert.True(ex.Stores["exch1.corp.local"].Any(c => c.Thumbprint == oldThumb), "altes bleibt (RemoveReplaced aus)");
    Assert.Equal("/tmp/haproxy/ssl/exch.pem", cfg.Selection.LastKnownPemPath, "Pfad gemerkt");
});

