Test("Config: Roundtrip mit Schutz", () =>
{
    var path = Path.Combine(Path.GetTempPath(), $"o2e-cfg-{Guid.NewGuid():N}.dat");
    var store = new ConfigStore(path, new ReverseProtector());
    var (cfg, _, _, _, _) = Scenario();
    cfg.OpnSense.PasswordProtected = store.Hide("geheim");
    store.Save(cfg);
    Assert.False(File.ReadAllText(path).Contains("mail.example.de"), "Datei nicht im Klartext");
    var loaded = store.Load();
    Assert.Equal("geheim", store.Reveal(loaded.OpnSense.PasswordProtected), "Passwort");
    Assert.Equal(2, loaded.Exchange.Servers.Count, "Server");
    File.Delete(path);
});

