Test("PEM: Leaf/Kette/Key erkennen + PFX-Roundtrip (RSA)", () =>
{
    var (pem, thumb) = pki.Leaf(new[] { "mail.example.de", "autodiscover.example.de" }, now.AddDays(-1), now.AddDays(89));
    using var b = CertificateBundle.Parse(pem, "test");
    Assert.Equal(thumb, b.Info.Thumbprint, "Leaf erkannt");
    Assert.True(b.HasPrivateKey, "Key");
    Assert.Equal(1, b.Chain.Count, "Kette");
    Assert.Equal("RSA 2048", b.Info.KeyAlgorithm, "Algorithmus");
    Assert.True(b.Info.Covers("autodiscover.example.de"), "SAN");

    var pwd = CertificateBundle.GeneratePassword();
    var pfx = b.ExportPfx(pwd);
    var col = X509CertificateLoader.LoadPkcs12Collection(pfx, pwd);
    Assert.Equal(2, col.Count, "PFX enthält Leaf + Intermediate");
    var leaf = col.Single(c => c.HasPrivateKey);
    Assert.Equal(thumb, leaf.Thumbprint, "PFX-Leaf-Thumbprint");
});

Test("PEM: Key vor Zertifikat, ECDSA", () =>
{
    var (pem, thumb) = pki.Leaf(new[] { "mail.example.de" }, now.AddDays(-1), now.AddDays(60), ecdsa: true, keyFirst: true);
    using var b = CertificateBundle.Parse(pem, "test");
    Assert.Equal(thumb, b.Info.Thumbprint, "Leaf");
    Assert.True(b.Info.IsEcdsa, "ECDSA");
    var v = CertificateValidator.Validate(b.Info, new[] { "mail.example.de" }, DateTime.Now);
    Assert.True(v.Ok, "gültig");
    Assert.True(v.Warnings.Any(w => w.Contains("ECDSA")), "ECDSA-Warnung");
    var pfx = b.ExportPfx("x");
    Assert.True(X509CertificateLoader.LoadPkcs12Collection(pfx, "x").Any(c => c.HasPrivateKey), "PFX mit ECDSA-Key");
});

Test("PEM: Ohne Key / falscher Key / leer", () =>
{
    var (pem, _) = pki.Leaf(new[] { "mail.example.de" }, now.AddDays(-1), now.AddDays(60), includeKey: false);
    using (var b = CertificateBundle.Parse(pem, "test")) Assert.False(b.HasPrivateKey, "kein Key");

    var (pemA, _) = pki.Leaf(new[] { "a.example.de" }, now.AddDays(-1), now.AddDays(60));
    var (pemB, _) = pki.Leaf(new[] { "b.example.de" }, now.AddDays(-1), now.AddDays(60), includeKey: false);
    var keyOfA = pemA[pemA.IndexOf("-----BEGIN PRIVATE KEY-----", StringComparison.Ordinal)..];
    Assert.Throws<System.Security.Cryptography.CryptographicException>(() => CertificateBundle.Parse(pemB + keyOfA, "mix"), "Key passt nicht");
    Assert.Throws<System.Security.Cryptography.CryptographicException>(() => CertificateBundle.Parse("garbage", "leer"), "keine Zertifikate");
});

