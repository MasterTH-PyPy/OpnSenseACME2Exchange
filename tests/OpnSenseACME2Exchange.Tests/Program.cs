Test("Tokenizer: Quotes, Escapes, Kommentare", () =>
{
    var t = HaproxyConfig.Tokenize("  http-request set-header X-Test \"a b\\\"c\" 'd e' # kommentar");
    Assert.Equal(5, t.Count, "Tokenanzahl");
    Assert.Equal("a b\"c", t[3], "doppelte Quotes");
