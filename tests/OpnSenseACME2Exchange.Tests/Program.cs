Test("Parser: Abschnitte, Binds, Hostnamen, Map-Dateien", () =>
{
    var cfg = HaproxyConfig.Parse(HaproxyConf);
    Assert.Equal(6, cfg.Sections.Count, "Abschnitte");
    var fe = cfg.Find("frontend 1_HTTPS_frontend") ?? throw new Exception("Frontend nicht gefunden");
    Assert.True(fe.TerminatesTls, "TLS");
    Assert.Equal("/tmp/haproxy/ssl/60a1b2c3.certlist", fe.Binds[0].CrtListPaths[0], "crt-list");
    Assert.True(fe.Hostnames.Contains("mail.example.de") && fe.Hostnames.Contains("autodiscover.example.de"), "Hostnamen aus hdr(host)");
    Assert.True(fe.ReferencedFiles.Contains("/tmp/haproxy/mapfiles/60a2.txt"), "Map-Datei");
    Assert.True(fe.LeadingComments.Any(c => c.Contains("Exchange und Co")), "OPNsense-Kommentar übernommen");

    var sni = cfg.Find("frontend 2_SNI")!;
    Assert.False(sni.TerminatesTls, "Passthrough terminiert kein TLS");
    Assert.True(sni.Hostnames.Contains("owa.example.de"), "Hostname aus req.ssl_sni");
    Assert.False(sni.Hostnames.Contains("1"), "req.ssl_hello_type liefert keinen Hostnamen");

    var direct = cfg.Find("frontend 3_DIRECT")!;
    Assert.Equal("/tmp/haproxy/ssl/direct.pem", direct.Binds[0].CrtPaths[0], "crt-Pfad trotz Kommentar");
    Assert.Equal(3, cfg.CertificateSections.Count(), "frontend/listen");
    Assert.True(cfg.Find("backend exchange_backend") != null, "Backend");
});

