// ───────────────────────── Entscheidung ─────────────────────────
CertificateInfo Info(string tp, int daysLeft, params string[] names) => new("CN=" + names[0], "CN=R1", tp, "01",
    DateTime.Now.AddDays(daysLeft - 90), DateTime.Now.AddDays(daysLeft), names, "RSA 2048", true, 1);
ExchangeCertInfo Ex(string tp, int daysLeft, string services, string issuer = "CN=R1", params string[] names) =>
    new(tp, "CN=" + (names.Length > 0 ? names[0] : "mail.example.de"), issuer, null, DateTime.Now.AddDays(daysLeft - 90), DateTime.Now.AddDays(daysLeft),
        ExchangeCertInfo.ParseServices(services), names.Length > 0 ? names : new[] { "mail.example.de" }, true);

var iis = new[] { "IIS" };
Test("Entscheidung: neuer → tauschen, älter → nicht", () =>
{
    var cand = Info("NEW", 89, "mail.example.de");
    var d = CertDecision.Decide(cand, new[] { Ex("OLD", 20, "IIS, SMTP") }, iis, "mail.example.de", DateTime.Now);
    Assert.Equal(DeployAction.Deploy, d.Action, "neuer");
    Assert.Equal("OLD", d.ReplacedCertificate!.Thumbprint, "ersetzt");

    var d2 = CertCandidateOlder();
    Assert.Equal(DeployAction.Skip, d2.Action, "älter");

    DeployDecision CertCandidateOlder() =>
        CertDecision.Decide(Info("NEW", 30, "mail.example.de"), new[] { Ex("BUY", 180, "IIS") }, iis, "mail.example.de", DateTime.Now);
});

Test("Entscheidung: gleicher Thumbprint, Dienste fehlen, selbstsigniert, abgelaufen", () =>
{
    var cand = Info("SAME", 60, "mail.example.de");
    Assert.Equal(DeployAction.Skip,
        CertDecision.Decide(cand, new[] { Ex("SAME", 60, "IIS,SMTP") }, new[] { "IIS", "SMTP" }, "mail.example.de", DateTime.Now).Action, "aktuell");
    Assert.Equal(DeployAction.EnableOnly,
        CertDecision.Decide(cand, new[] { Ex("SAME", 60, "None"), Ex("OLD", 10, "IIS") }, iis, "mail.example.de", DateTime.Now).Action, "nur aktivieren");
    Assert.Equal(DeployAction.Deploy,
        CertDecision.Decide(cand, new[] { Ex("SELF", 1800, "IIS,SMTP", "CN=EXCH01", "EXCH01") }, iis, "mail.example.de", DateTime.Now).Action,
        "Self-signed deckt Hostnamen nicht ab");
    Assert.Equal(DeployAction.Deploy,
        CertDecision.Decide(cand, Array.Empty<ExchangeCertInfo>(), iis, "mail.example.de", DateTime.Now).Action, "kein aktives");
    Assert.Equal(DeployAction.Skip,
        CertDecision.Decide(cand, Array.Empty<ExchangeCertInfo>(), Array.Empty<string>(), "mail.example.de", DateTime.Now).Action, "keine Dienste");
});

Test("Entscheidung: Entfernen nur wenn eindeutig", () =>
{
    var cand = Info("NEW", 89, "mail.example.de");
    Assert.True(CertDecision.MayRemove(Ex("OLD", 10, "IIS"), cand, iis, "mail.example.de"), "alte Version");
    Assert.False(CertDecision.MayRemove(Ex("OLD", 10, "IIS,SMTP"), cand, iis, "mail.example.de"), "SMTP hängt noch dran");
    Assert.False(CertDecision.MayRemove(Ex("SELF", 10, "IIS", "CN=mail.example.de"), cand, iis, "mail.example.de"), "selbstsigniert");
    Assert.False(CertDecision.MayRemove(Ex("OTHER", 10, "IIS", "CN=R1", "www.example.de"), cand, iis, "mail.example.de"), "anderer Name");
});

