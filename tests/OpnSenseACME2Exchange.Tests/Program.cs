sealed class ReverseProtector : ISecretProtector
{
    public string Protect(string plain) => "P:" + Convert.ToBase64String(System.Text.Encoding.UTF8.GetBytes(new string(plain.Reverse().ToArray())));
    public string Unprotect(string p) => new(System.Text.Encoding.UTF8.GetString(Convert.FromBase64String(p[2..])).Reverse().ToArray());
}
